"""Bundle the sidecar's runtime dependencies as one hash-pinned requirements file.

`uv.lock` is the source of truth for what the sidecar runs on. `vendor/requirements.txt` is the same
set, rendered for `pip`: exact versions and every artifact hash the lock records, for the closure
walked from the sidecar's own runtime dependencies — no dev group, no project, extras included
(`jev-ultrafast` asks for `httpx[http2]`, so `h2` and its dependencies are part of it).

Why a second file at all: uv is not the only way to build the environment. A machine that already has
Python 3.12+ (DSH ships one) needs no uv, no Python download, and no project build — only this file
and the wheels it names. `pip install --require-hashes --no-deps` then gives the guarantee
`uv sync --frozen` gives: the artifacts are the ones the lock recorded, byte for byte.

Two things the lock installs are deliberately not in the file:

* `pillow` — the difference between a 5.8 MB first install and a 1.3 MB one. Browser Harness declares
  it for its screenshot-annotation and video helpers; the sidecar imports `browser_harness._ipc`,
  `admin`, `helpers` and `daemon`, none of which touch PIL at import time, captures its JPEGs over CDP
  itself, and runs the engine with `screenshots=False`. To put it back, `pip install pillow==<the
  lock's version>` into the environment the doctor names, or `uv sync --frozen` in a checkout.
* `jev-ultrafast` — the engine ships as a wheel inside this package, so there is no index to fetch it
  from. The plugin installs `vendor/jev_ultrafast-<version>-py3-none-any.whl` itself, offline, right
  after this file.

  uv run python bin/vendor_requirements.py update    # re-render from uv.lock
  uv run python bin/vendor_requirements.py check     # what CI runs: the file still matches the lock
"""

import argparse
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCK = ROOT / "uv.lock"
REQUIREMENTS = ROOT / "vendor" / "requirements.txt"
PROJECT = "dsh-browser-use-sidecar"

# What the lock installs and this file does not, each with the reason it is safe — or handled — elsewhere.
SKIPPED = {
    "pillow": "Browser Harness's screenshot helpers; this plugin never calls them (see the module docstring)",
    "jev-ultrafast": "ships as a wheel in this package; the plugin installs it offline, not pip",
}

HEADER = """\
# Generated by bin/vendor_requirements.py from uv.lock — edit the lock, then re-run `update`.
#
# The sidecar's runtime dependencies, pinned by version and by the hash of every artifact the lock
# records. `pip install --require-hashes --no-deps --only-binary=:all: -r this-file` builds what
# `uv sync --frozen` builds, without uv: any Python 3.12+ can run it.
#
# Not listed, on purpose:
{skipped}
"""


def closure(lock):
    """The packages the sidecar imports at run time: the project's dependencies, extras and all."""
    packages = {item["name"]: item for item in lock["package"]}
    wanted, seen, pending = {}, set(), [(PROJECT, None)]
    while pending:
        name, extra = pending.pop()
        if (name, extra) in seen:
            continue
        seen.add((name, extra))
        package = packages[name]
        if name != PROJECT:
            wanted[name] = package
        edges = (package.get("dependencies", []) if extra is None
                 else package.get("optional-dependencies", {}).get(extra, []))
        for edge in edges:
            pending.append((edge["name"], None))
            pending.extend((edge["name"], item) for item in edge.get("extra", []))
    return wanted


def hashes(package):
    """Every hash the lock records for one package, sdist first, without repeats."""
    values = []
    for artifact in [package.get("sdist", {}), *package.get("wheels", [])]:
        if artifact.get("hash") and artifact["hash"] not in values:
            values.append(artifact["hash"])
    return values


def render(root=ROOT):
    """The requirements file as text: every package, every hash, one version each."""
    lock = tomllib.loads((root / "uv.lock").read_text())
    packages = {name: package for name, package in closure(lock).items() if name not in SKIPPED}
    lines = [HEADER.format(skipped="\n".join(f"#   {name}: {why}" for name, why in SKIPPED.items()))]
    for name in sorted(packages):
        package = packages[name]
        values = hashes(package)
        if not values:
            raise SystemExit(f"{name} has no recorded hashes in uv.lock; the lock is not installable by hash.")
        if len(values) == 1:
            lines.append(f"{name}=={package['version']} --hash={values[0]}")
            continue
        lines.append(f"{name}=={package['version']} \\")
        lines.extend(f"    --hash={value}{' \\' if index < len(values) - 1 else ''}"
                     for index, value in enumerate(values))
    return "\n".join(lines) + "\n"


def update():
    text = render()
    REQUIREMENTS.parent.mkdir(parents=True, exist_ok=True)
    REQUIREMENTS.write_text(text)
    print(f"Wrote {REQUIREMENTS.relative_to(ROOT)}: {text.count('==')} packages, {text.count('--hash=')} hashes.")


def check():
    text = render()
    if not REQUIREMENTS.exists():
        raise SystemExit(f"{REQUIREMENTS.relative_to(ROOT)} is missing; run bin/vendor_requirements.py update.")
    if REQUIREMENTS.read_text() != text:
        raise SystemExit(f"{REQUIREMENTS.relative_to(ROOT)} no longer matches uv.lock; "
                         "run bin/vendor_requirements.py update and commit both.")
    print(f"{REQUIREMENTS.relative_to(ROOT)} matches uv.lock: "
          f"{text.count('==')} pinned packages, {text.count('--hash=')} hashes.")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=["update", "check"])
    args = parser.parse_args()
    (update if args.command == "update" else check)()


if __name__ == "__main__":
    main()
